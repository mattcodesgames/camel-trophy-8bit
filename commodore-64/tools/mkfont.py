upper_order = '@ABCDEFGHIJKLMNOPQRSTUVWXYZ[£]↑← !"#$%&\'()*+,-./0123456789:;<=>?'
def build(lowercase):
    out = []
    for c in range(128):
        if c < 64:
            ch = upper_order[c]
            if lowercase and 1 <= c <= 26:
                ch = ch.lower()
            out.append(G[ch])
        elif lowercase and 65 <= c <= 90:
            out.append(G[upper_order[c - 64]])
        elif lowercase and c == 64:
            out.append(gfx[64])
        else:
            out.append(gfx[c])
    out += [[r ^ 0xFF for r in glyph] for glyph in out]
    return [b for glyph in out for b in glyph]

